const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();
const attributes = ['aria-label', 'alt', 'placeholder', 'title', 'content'];

export const getLanguage = () => language;
export function localizeCanvas(ctx) {
  const fillText = ctx.fillText.bind(ctx);
  ctx.fillText = (value, x, y, maxWidth) => {
    const available = maxWidth ?? (ctx.textAlign === 'center' ? ctx.canvas.width - 32 : ctx.textAlign === 'right' || ctx.textAlign === 'end' ? x - 16 : ctx.canvas.width - x - 16);
    fillText(t(value), x, y, Math.max(20, available));
  };
  return ctx;
}
export function t(value, selected = language) {
  if (selected === 'en' || typeof value !== 'string') return value;
  const direct = translations.get(value)?.[selected];
  if (direct !== undefined) return direct;
  const numbered = value.match(/^(\d{2}) \/ (POSSIBLE|REVIEW|SHORTLIST|YOUR PROFILE|YOUR DESTINATION|YOUR UNIVERSITY|YOUR DOCUMENTS|YOUR APPLICATION|YOUR ADMISSION|YOUR VISA|YOUR DEPARTURE)$/);
  if (numbered) return `${numbered[1]} / ${t(numbered[2], selected)}`;
  const university = value.match(/^UNIVERSITY (\d{2})$/);
  if (university) return `${t('UNIVERSITY', selected)} ${university[1]}`;
  const reference = value.match(/^REFERENCE \/ (\d{2})$/);
  if (reference) return `${selected === 'uz' ? 'HAVOLA' : 'НОМЕР'} / ${reference[1]}`;
  const credit = value.match(/^(PHOTO|ILLUSTRATIVE STUDENT LIFE) — (.+)$/);
  if (credit) return `${selected === 'uz' ? credit[1] === 'PHOTO' ? 'FOTO' : 'NAMUNAVIY TALABALAR HAYOTI' : credit[1] === 'PHOTO' ? 'ФОТО' : 'ПРИМЕР СТУДЕНЧЕСКОЙ ЖИЗНИ'} — ${credit[2]}`;
  return value;
}

function translateText(node) {
  if (!node.parentElement || node.parentElement.closest('script,style,[data-no-translate]')) return;
  const current = node.nodeValue;
  const saved = sourceText.get(node);
  if (saved === undefined || current !== t(saved) && current !== saved) sourceText.set(node, current);
  const source = sourceText.get(node);
  const trimmed = source.trim();
  if (!trimmed) return;
  const translated = t(trimmed);
  const next = source.replace(trimmed, translated);
  if (current !== next) node.nodeValue = next;
}

function translateAttributes(node) {
  if (node.closest('[data-no-translate]')) return;
  let saved = sourceAttributes.get(node);
  if (!saved) { saved = new Map(); sourceAttributes.set(node, saved); }
  for (const name of attributes) {
    if (!node.hasAttribute(name)) continue;
    const current = node.getAttribute(name);
    const previous = saved.get(name);
    if (previous === undefined || current !== t(previous) && current !== previous) saved.set(name, current);
    const next = t(saved.get(name));
    if (current !== next) node.setAttribute(name, next);
  }
}

export function translateDOM(root = document.documentElement) {
  if (root.nodeType === Node.TEXT_NODE) { translateText(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  translateAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.nodeType === Node.TEXT_NODE) translateText(node);
    else translateAttributes(node);
  }
  document.documentElement.lang = language;
  document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
}

export function initI18n() {
  translateDOM();
  applyEditorialCopy(language);
  document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => {
    const next = button.dataset.language;
    if (next === language) return;
    try {
      localStorage.setItem(storageKey, next);
      sessionStorage.setItem('nord-language-scroll', String(window.scrollY));
      sessionStorage.setItem('nord-language-stage', document.documentElement.dataset.cinematicStage || 'decision-intro');
      sessionStorage.setItem('nord-language-normal', String(document.documentElement.classList.contains('is-normal-scroll')));
    } catch {}
    window.location.reload(); // Recreate translated canvas textures as well as HTML text.
  }));
  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateText(record.target);
      else if (record.type === 'attributes') translateAttributes(record.target);
      else for (const node of record.addedNodes) translateDOM(node);
    }
  });
  observer.observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributes });
  const savedScroll = (() => { try { const value = sessionStorage.getItem('nord-language-scroll'); sessionStorage.removeItem('nord-language-scroll'); return value === null ? null : Number(value); } catch { return null; } })();
  let restoreNormal = false;
  try { restoreNormal = sessionStorage.getItem('nord-language-normal') === 'true'; } catch {}
  if (restoreNormal && savedScroll !== null && Number.isFinite(savedScroll)) window.addEventListener('load', () => requestAnimationFrame(() => window.scrollTo(0, savedScroll)), { once: true });
}
